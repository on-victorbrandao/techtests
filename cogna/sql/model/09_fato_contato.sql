-- fato contato: grao = 1 linha por contato_id, unificando os 4 canais (5.991 registros) sem aluno_id_original
CREATE OR REPLACE TABLE fato_contato AS
WITH uniao AS (
    -- Call Center
    SELECT
        contato_id,
        aluno_hash,
        canal,
        data_hora_contato,
        duracao_s,
        CAST(NULL AS INTEGER) AS tme_s,
        nota,
        status_nota,
        respondeu_pesquisa,
        flag_nota_ruim,
        flag_duracao_zero,
        flag_outlier_duracao,
        CAST(FALSE AS BOOLEAN) AS flag_outlier_tme,
        CAST(FALSE AS BOOLEAN) AS flag_tme_maior_duracao,
        recepcao_fila,
        fila_atend,
        flag_filas_divergentes,
        eh_retencao_fila,
        eh_assunto_retencao,
        flag_encaminhamento_retencao,
        flag_retencao_protocolo,
        desfecho_retencao,
        formato_protocolo,
        protocolo_padrao_cs,
        qtd_niveis_tab,
        modalidade_tab,
        flag_divergencia_modalidade,
        qtd_passos_original,
        flag_dominio_inconsistente,
        origem_aba,
        origem_linha,
        agente_original,
        id_type_codigo,
        COALESCE(id_type_rotulo, id_type_rotulo_original, 'Não Informado no Canal') AS id_type_rotulo,
        modalidade_codigo,
        COALESCE(modalidade_rotulo, modalidade_rotulo_original, 'Não Informado no Canal') AS modalidade_rotulo,
        categoria_aluno_codigo,
        COALESCE(categoria_aluno_rotulo, categoria_aluno_rotulo_original, 'Não Informado no Canal') AS categoria_aluno_rotulo,
        instituicao_codigo,
        COALESCE(instituicao_rotulo, instituicao_rotulo_original, 'Não Informado no Canal') AS instituicao_rotulo,
        'tabulacao' AS taxonomia_motivo,
        tabulacao_original,
        CAST(NULL AS VARCHAR) AS mdc_original
    FROM silver_callcenter
    UNION ALL
    -- WhatsApp
    SELECT
        contato_id,
        aluno_hash,
        canal,
        data_hora_contato,
        duracao_s,
        tme_s,
        nota,
        status_nota,
        respondeu_pesquisa,
        flag_nota_ruim,
        flag_duracao_zero,
        flag_outlier_duracao,
        flag_outlier_tme,
        flag_tme_maior_duracao,
        CAST(NULL AS VARCHAR) AS recepcao_fila,
        CAST(NULL AS VARCHAR) AS fila_atend,
        CAST(FALSE AS BOOLEAN) AS flag_filas_divergentes,
        CAST(FALSE AS BOOLEAN) AS eh_retencao_fila,
        eh_assunto_retencao,
        flag_encaminhamento_retencao,
        CAST(FALSE AS BOOLEAN) AS flag_retencao_protocolo,
        desfecho_retencao,
        'nao_aplicavel' AS formato_protocolo,
        CAST(FALSE AS BOOLEAN) AS protocolo_padrao_cs,
        qtd_niveis_tab,
        modalidade_tab,
        flag_divergencia_modalidade,
        qtd_passos_original,
        flag_dominio_inconsistente,
        origem_aba,
        origem_linha,
        agente_original,
        id_type_codigo,
        COALESCE(id_type_rotulo, 'Não Informado no Canal') AS id_type_rotulo,
        modalidade_codigo,
        COALESCE(modalidade_rotulo, modalidade_rotulo_original, 'Não Informado no Canal') AS modalidade_rotulo,
        categoria_aluno_codigo,
        COALESCE(categoria_aluno_rotulo, categoria_aluno_rotulo_original, 'Não Informado no Canal') AS categoria_aluno_rotulo,
        instituicao_codigo,
        COALESCE(instituicao_rotulo, instituicao_rotulo_original, 'Não Informado no Canal') AS instituicao_rotulo,
        'tabulacao' AS taxonomia_motivo,
        tabulacao_original,
        CAST(NULL AS VARCHAR) AS mdc_original
    FROM silver_whatsapp
    UNION ALL
    -- Video Chamada
    SELECT
        contato_id,
        aluno_hash,
        canal,
        data_hora_contato,
        duracao_s,
        tme_s,
        nota,
        status_nota,
        respondeu_pesquisa,
        flag_nota_ruim,
        flag_duracao_zero,
        flag_outlier_duracao,
        flag_outlier_tme,
        flag_tme_maior_duracao,
        CAST(NULL AS VARCHAR) AS recepcao_fila,
        CAST(NULL AS VARCHAR) AS fila_atend,
        CAST(FALSE AS BOOLEAN) AS flag_filas_divergentes,
        CAST(FALSE AS BOOLEAN) AS eh_retencao_fila,
        eh_assunto_retencao,
        flag_encaminhamento_retencao,
        flag_retencao_protocolo,
        desfecho_retencao,
        formato_protocolo,
        protocolo_padrao_cs,
        qtd_niveis_tab,
        modalidade_tab,
        CAST(FALSE AS BOOLEAN) AS flag_divergencia_modalidade,
        CAST(NULL AS INTEGER) AS qtd_passos_original,
        CAST(FALSE AS BOOLEAN) AS flag_dominio_inconsistente,
        origem_aba,
        origem_linha,
        agente_original,
        CAST(NULL AS INTEGER) AS id_type_codigo,
        'Não Informado no Canal' AS id_type_rotulo,
        CAST(NULL AS INTEGER) AS modalidade_codigo,
        'Não Informado no Canal' AS modalidade_rotulo,
        CAST(NULL AS INTEGER) AS categoria_aluno_codigo,
        'Não Informado no Canal' AS categoria_aluno_rotulo,
        CAST(NULL AS INTEGER) AS instituicao_codigo,
        'Não Informado no Canal' AS instituicao_rotulo,
        'tabulacao' AS taxonomia_motivo,
        tabulacao_original,
        CAST(NULL AS VARCHAR) AS mdc_original
    FROM silver_video_chamada
    UNION ALL
    -- Totem
    SELECT
        contato_id,
        aluno_hash,
        canal,
        data_hora_contato,
        duracao_s,
        CAST(NULL AS INTEGER) AS tme_s,
        nota,
        status_nota,
        respondeu_pesquisa,
        flag_nota_ruim,
        flag_duracao_zero,
        flag_outlier_duracao,
        CAST(FALSE AS BOOLEAN) AS flag_outlier_tme,
        CAST(FALSE AS BOOLEAN) AS flag_tme_maior_duracao,
        CAST(NULL AS VARCHAR) AS recepcao_fila,
        CAST(NULL AS VARCHAR) AS fila_atend,
        CAST(FALSE AS BOOLEAN) AS flag_filas_divergentes,
        CAST(FALSE AS BOOLEAN) AS eh_retencao_fila,
        CAST(FALSE AS BOOLEAN) AS eh_assunto_retencao,
        CAST(FALSE AS BOOLEAN) AS flag_encaminhamento_retencao,
        CAST(FALSE AS BOOLEAN) AS flag_retencao_protocolo,
        CAST(NULL AS VARCHAR) AS desfecho_retencao,
        'nao_aplicavel' AS formato_protocolo,
        CAST(FALSE AS BOOLEAN) AS protocolo_padrao_cs,
        0 AS qtd_niveis_tab,
        CAST(NULL AS VARCHAR) AS modalidade_tab,
        CAST(FALSE AS BOOLEAN) AS flag_divergencia_modalidade,
        qtd_passos_original,
        CAST(FALSE AS BOOLEAN) AS flag_dominio_inconsistente,
        origem_aba,
        origem_linha,
        CAST(NULL AS VARCHAR) AS agente_original,
        CAST(NULL AS INTEGER) AS id_type_codigo,
        'Não Informado no Canal' AS id_type_rotulo,
        CAST(NULL AS INTEGER) AS modalidade_codigo,
        'Não Informado no Canal' AS modalidade_rotulo,
        CAST(NULL AS INTEGER) AS categoria_aluno_codigo,
        'Não Informado no Canal' AS categoria_aluno_rotulo,
        CAST(NULL AS INTEGER) AS instituicao_codigo,
        COALESCE(instituicao_original, 'Não Informado no Canal') AS instituicao_rotulo,
        'mdc' AS taxonomia_motivo,
        CAST(NULL AS VARCHAR) AS tabulacao_original,
        mdc_original
    FROM silver_totem
)
SELECT
    CAST(u.contato_id AS VARCHAR) AS contato_id,
    CAST(u.aluno_hash AS VARCHAR) AS aluno_hash,
    CAST(dc.canal_id AS INTEGER) AS canal_id,
    CAST(u.canal AS VARCHAR) AS canal,
    CAST(CAST(u.data_hora_contato AS DATE) AS DATE) AS data_contato,
    CAST(hour(u.data_hora_contato) AS INTEGER) AS hora_inteira,
    CAST(COALESCE(da.agente_id, 'AG-000') AS VARCHAR) AS agente_id,
    CAST(COALESCE(df.fila_id, 'FL-00') AS VARCHAR) AS fila_id,
    CAST(dp.perfil_id AS VARCHAR) AS perfil_id,
    CAST(dm.motivo_id AS VARCHAR) AS motivo_id,
    CAST(u.data_hora_contato AS TIMESTAMP) AS data_hora_contato,
    CAST(u.duracao_s AS INTEGER) AS duracao_s,
    CAST(u.tme_s AS INTEGER) AS tme_s,
    CAST(u.nota AS INTEGER) AS nota,
    CAST(u.status_nota AS VARCHAR) AS status_nota,
    CAST(u.respondeu_pesquisa AS BOOLEAN) AS respondeu_pesquisa,
    CAST(u.flag_nota_ruim AS BOOLEAN) AS flag_nota_ruim,
    CAST(u.flag_duracao_zero AS BOOLEAN) AS flag_duracao_zero,
    CAST(u.flag_outlier_duracao AS BOOLEAN) AS flag_outlier_duracao,
    CAST(u.flag_outlier_tme AS BOOLEAN) AS flag_outlier_tme,
    CAST(u.flag_tme_maior_duracao AS BOOLEAN) AS flag_tme_maior_duracao,
    CAST(u.recepcao_fila AS VARCHAR) AS recepcao_fila,
    CAST(u.fila_atend AS VARCHAR) AS fila_atend,
    CAST(u.flag_filas_divergentes AS BOOLEAN) AS flag_filas_divergentes,
    CAST(u.eh_retencao_fila AS BOOLEAN) AS eh_retencao_fila,
    CAST(u.eh_assunto_retencao AS BOOLEAN) AS eh_assunto_retencao,
    CAST(u.flag_encaminhamento_retencao AS BOOLEAN) AS flag_encaminhamento_retencao,
    CAST(u.flag_retencao_protocolo AS BOOLEAN) AS flag_retencao_protocolo,
    CAST(u.desfecho_retencao AS VARCHAR) AS desfecho_retencao,
    CAST(u.formato_protocolo AS VARCHAR) AS formato_protocolo,
    CAST(u.protocolo_padrao_cs AS BOOLEAN) AS protocolo_padrao_cs,
    CAST(u.qtd_niveis_tab AS INTEGER) AS qtd_niveis_tab,
    CAST(u.modalidade_tab AS VARCHAR) AS modalidade_tab,
    CAST(u.flag_divergencia_modalidade AS BOOLEAN) AS flag_divergencia_modalidade,
    CAST(u.qtd_passos_original AS INTEGER) AS qtd_passos_original,
    CAST(u.flag_dominio_inconsistente AS BOOLEAN) AS flag_dominio_inconsistente,
    CAST(u.origem_aba AS VARCHAR) AS origem_aba,
    CAST(u.origem_linha AS INTEGER) AS origem_linha
FROM uniao AS u
INNER JOIN dim_canal AS dc
    ON dc.canal = u.canal
LEFT JOIN dim_agente AS da
    ON da.canal_agente = u.canal
   AND da.agente_hash = substr(sha256(u.agente_original), 1, 12)
LEFT JOIN dim_fila AS df
    ON u.canal = 'call_center'
   AND df.recepcao_fila = COALESCE(u.recepcao_fila, 'Sem Recepção Fila')
   AND df.fila_atend = COALESCE(u.fila_atend, 'Sem Fila Atendimento')
INNER JOIN dim_perfil_aluno AS dp
    ON dp.canal_perfil = u.canal
   AND dp.id_type_codigo IS NOT DISTINCT FROM u.id_type_codigo
   AND dp.modalidade_codigo IS NOT DISTINCT FROM u.modalidade_codigo
   AND dp.categoria_aluno_codigo IS NOT DISTINCT FROM u.categoria_aluno_codigo
   AND dp.instituicao_codigo IS NOT DISTINCT FROM u.instituicao_codigo
   AND dp.instituicao_rotulo IS NOT DISTINCT FROM u.instituicao_rotulo
INNER JOIN dim_motivo AS dm
    ON dm.taxonomia_motivo = u.taxonomia_motivo
   AND dm.tabulacao_original IS NOT DISTINCT FROM u.tabulacao_original
   AND dm.mdc_original IS NOT DISTINCT FROM u.mdc_original
ORDER BY u.canal, u.origem_linha;
